<?php

namespace App\Commands;

use CodeIgniter\CLI\BaseCommand;
use CodeIgniter\CLI\CLI;

class DbBackup extends BaseCommand
{
    /**
     * The Command's Group
     *
     * @var string
     */
    protected $group = 'Database';

    /**
     * The Command's Name
     *
     * @var string
     */
    protected $name = 'db:backup';

    /**
     * The Command's Description
     *
     * @var string
     */
    protected $description = 'Membuat backup database MySQL otomatis ke folder writable/backups.';

    /**
     * The Command's Usage
     *
     * @var string
     */
    protected $usage = 'command:name [arguments] [options]';

    /**
     * The Command's Arguments
     *
     * @var array
     */
    protected $arguments = [];

    /**
     * The Command's Options
     *
     * @var array
     */
    protected $options = [];

    /**
     * Actually execute a command.
     *
     * @param array $params
     */
    public function run(array $params)
    {
        $db       = \Config\Database::connect();
        $database = $db->getDatabase();

        $backupDir = WRITEPATH . 'backups/';
        if (!is_dir($backupDir)) {
            mkdir($backupDir, 0777, true);
        }

        $filename = 'backup_' . $database . '_' . date('Ymd_His') . '.sql';
        $filepath = $backupDir . $filename;

        try {
            $tables = [];
            $query  = $db->query("SHOW TABLES");
            foreach ($query->getResultArray() as $row) {
                $tables[] = reset($row);
            }

            $sqlScript = "-- Database Backup generated by CodeIgniter 4\n";
            $sqlScript .= "-- Date: " . date('Y-m-d H:i:s') . "\n\n";
            $sqlScript .= "SET FOREIGN_KEY_CHECKS=0;\n\n";

            foreach ($tables as $table) {
                // Struktur Tabel
                $row = $db->query("SHOW CREATE TABLE `{$table}`")->getRowArray();
                $sqlScript .= "\n\n" . $row['Create Table'] . ";\n\n";

                // Isi Data Tabel
                $rows = $db->table($table)->get()->getResultArray();
                foreach ($rows as $data) {
                    $fields = array_keys($data);
                    $values = array_values($data);

                    // Escape values
                    $escapedValues = array_map(function ($val) use ($db) {
                        if ($val === null) return 'NULL';
                        return $db->escape($val);
                    }, $values);

                    $sqlScript .= "INSERT INTO `{$table}` (`" . implode('`, `', $fields) . "`) VALUES (" . implode(', ', $escapedValues) . ");\n";
                }
            }

            $sqlScript .= "\nSET FOREIGN_KEY_CHECKS=1;\n";

            if (file_put_contents($filepath, $sqlScript) !== false) {
                CLI::write("Backup database via PHP berhasil disimpan di: {$filepath}", 'green');
                $this->cleanOldBackups($backupDir, 7);
            } else {
                CLI::error("Gagal menulis file backup ke disk.");
            }
        } catch (\Throwable $e) {
            CLI::error("Gagal melakukan backup database: " . $e->getMessage());
        }
    }

    protected function cleanOldBackups(string $dir, int $days = 7)
    {
        $files = glob($dir . '*.sql');
        $now   = time();
        foreach ($files as $file) {
            if (is_file($file)) {
                if ($now - filemtime($file) >= 60 * 60 * 24 * $days) {
                    @unlink($file);
                }
            }
        }
    }
}
